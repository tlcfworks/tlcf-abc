import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startServer } from '../src/server.ts';
import { Service } from '../src/service.ts';
import { request } from 'node:http';
test('HTTP enforces loopback host, origin, CSRF, safe static paths and account bounds', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'quota-http-')); const service = new Service(dir);
  const { server, origin } = await startServer(0, service);
  t.after(async () => { await new Promise<void>(resolve => server.close(() => resolve())); await rm(dir, { recursive: true, force: true }); });
  assert.equal((server.address() as any).address, '127.0.0.1');
  const home = await fetch(origin); assert.equal(home.status, 200); assert.ok(home.headers.get('content-security-policy')?.includes("frame-ancestors 'none'")); assert.ok((await home.text()).includes('ABC'));
  const badHost = await new Promise<number | undefined>((resolve, reject) => { const req = request(origin + '/api/state', { headers: { Host: 'evil.test' } }, res => { res.resume(); resolve(res.statusCode); }); req.on('error', reject); req.end(); });
  assert.equal(badHost, 403);
  assert.equal((await fetch(`${origin}/api/state`, { headers: { Origin: 'https://evil.test' } })).status, 403);
  assert.equal((await fetch(`${origin}/api/state`, { headers: { 'Sec-Fetch-Site': 'cross-site' } })).status, 403);
  assert.equal((await fetch(`${origin}/src/server.ts`)).status, 404);
  const { token } = await (await fetch(`${origin}/api/state`)).json();
  const headers = { Origin: origin, 'Content-Type': 'application/json', 'X-Quota-Desk': token };
  assert.equal((await fetch(`${origin}/api/refresh`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  const post = (path: string, data: any) => fetch(origin + path, { method: 'POST', headers, body: JSON.stringify(data) });
  assert.equal((await post('/api/accounts', { provider: 'other', name: 'Invalid' })).status, 400);
  assert.equal((await post('/api/accounts', { provider: 'codex', name: 'Invalid', profilePath: 'relative/path' })).status, 400);
  const created = await (await post('/api/accounts/new-codex', { name: 'Isolated' })).json();
  const a = service.accounts[0]; assert.equal(a.managed, true); assert.ok(a.profilePath.startsWith(dir));
  const config = await readFile(join(a.profilePath, 'config.toml'), 'utf8'); assert.ok(config.includes('"keyring"')); assert.ok(!config.includes('auto'));
  assert.ok(created.launcherPath.startsWith(a.profilePath)); assert.equal((await post('/api/accounts/new-codex', { name: 'Second' })).status, 200);
  assert.equal((await post('/api/accounts/new-codex', { name: 'Third' })).status, 400);
  assert.equal((await post(`/api/accounts/${a.id}/remove`, {})).status, 200); assert.ok(await readFile(join(a.profilePath, 'config.toml'), 'utf8'));
});
