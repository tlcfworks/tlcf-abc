import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { collectorSetup, enableCollector, disableCollector } from '../src/integration.ts';
import type { Account } from '../src/types.ts';
test('monitoring preserves original status output, unrelated settings and edits made after enable', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'abc-enable-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const profile = join(dir, 'profile'); await mkdir(profile);
  const a: Account = { id: randomUUID(), provider: 'antigravity', name: 'A', profilePath: profile, managed: false };
  await writeFile(join(dir, 'accounts.json'), JSON.stringify([a]));
  const original = { theme: 'custom', statusLine: { type: 'command', command: 'echo original-status', padding: 2 } };
  await writeFile(join(profile, 'settings.json'), JSON.stringify(original));
  assert.equal((await collectorSetup(a, dir)).enabled, false);
  await enableCollector(a, dir); await enableCollector(a, dir);
  assert.equal((await collectorSetup(a, dir)).enabled, true);
  const settings = JSON.parse(await readFile(join(profile, 'settings.json'), 'utf8'));
  assert.equal(settings.theme, 'custom'); assert.equal(settings.statusLine.padding, 2);
  const command = settings.statusLine.command.split(' ');
  const result = spawnSync(command[0], command.slice(1), { encoding: 'utf8', input: JSON.stringify({ email: 'a@example.test', quota: { weekly: { remaining_fraction: .6, reset_time: '2030-01-01T00:00:00Z' } } }), windowsHide: true });
  assert.equal(result.status, 0, result.stderr); assert.equal(result.stdout.trim(), 'original-status');
  const snapshot = JSON.parse(await readFile(join(dir, 'snapshots', `${a.id}.json`), 'utf8')); assert.equal(snapshot.quotas[0].remainingPercent, 60);
  settings.theme = 'edited-while-enabled'; await writeFile(join(profile, 'settings.json'), JSON.stringify(settings));
  await disableCollector(a, dir);
  assert.deepEqual(JSON.parse(await readFile(join(profile, 'settings.json'), 'utf8')), { ...original, theme: 'edited-while-enabled' });
  await disableCollector(a, dir);
});
test('monitoring refuses invalid settings and outside status-line changes', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'abc-conflict-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const a: Account = { id: randomUUID(), provider: 'antigravity', name: 'A', profilePath: dir, managed: false };
  await writeFile(join(dir, 'settings.json'), '{invalid');
  await assert.rejects(() => enableCollector(a, dir), /not valid JSON/);
  assert.equal(await readFile(join(dir, 'settings.json'), 'utf8'), '{invalid');
  await writeFile(join(dir, 'settings.json'), '{}'); await enableCollector(a, dir);
  await writeFile(join(dir, 'settings.json'), JSON.stringify({ statusLine: { command: 'echo external-edit' } }));
  await assert.rejects(() => disableCollector(a, dir), /changed outside ABC/);
  await assert.rejects(() => enableCollector(a, dir), /changed outside ABC/);
  assert.ok((await readFile(join(dir, 'settings.json'), 'utf8')).includes('external-edit'));
});
